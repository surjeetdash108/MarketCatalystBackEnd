/**
 * Writes the plan catalog from src/plans/plans.registry.ts (the source of
 * truth) into the copies other repos read at build time:
 *
 *   ../MarketCatalystUI/app/admin/entitlement-catalog.ts   entitlement keys/labels
 *   ../MarketCatalystWebsite/lib/pricing/catalog.json        plans + prices (fallback
 *                                                            when GET /plans is down)
 *
 *   npx ts-node --transpile-only scripts/export-catalog.ts [--check]
 *
 * --check exits 1 if either copy is out of date (used by the contract test).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import {
  CATALOG_VERSION,
  ENTITLEMENTS,
  PLAN_DEFINITIONS,
} from "../src/plans/plans.registry";

const ROOT = join(__dirname, "..", "..");
const UI_CATALOG = join(
  ROOT,
  "MarketCatalystUI/app/admin/entitlement-catalog.ts",
);
const WEB_CATALOG = join(
  ROOT,
  "MarketCatalystWebsite/lib/pricing/catalog.json",
);

export function uiCatalogSource(): string {
  const rows = ENTITLEMENTS.map(
    (e) =>
      "  { " +
      Object.entries(e)
        .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
        .join(", ") +
      " },",
  ).join("\n");
  return `// GENERATED by MarketCatalystBackEnd/scripts/export-catalog.ts from
// src/plans/plans.registry.ts — do not edit by hand; re-run the script.

export interface EntitlementDef {
  key: string;
  label: string;
  /** One plain sentence: what the user gets when this is ON. */
  description: string;
  group: string;
  staffOnly?: boolean;
  unbuilt?: boolean;
  note?: string;
}

export const ENTITLEMENTS: EntitlementDef[] = [
${rows}
];
`;
}

export function websiteCatalogJson(): string {
  const plans = PLAN_DEFINITIONS.filter((p) => p.active).map((p) => ({
    id: p.id,
    name: p.name,
    description: p.description,
    currency: p.currency,
    prices: p.prices,
  }));
  return (
    JSON.stringify({ catalogVersion: CATALOG_VERSION, plans }, null, 2) + "\n"
  );
}

function main() {
  const check = process.argv.includes("--check");
  const targets: Array<[string, string]> = [
    [UI_CATALOG, uiCatalogSource()],
    [WEB_CATALOG, websiteCatalogJson()],
  ];
  let stale = 0;
  for (const [path, content] of targets) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === content) continue;
    if (check) {
      console.error(`out of date: ${path}`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${path}`);
    }
  }
  if (check && stale) process.exit(1);
}

if (require.main === module) main();
