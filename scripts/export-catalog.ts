/**
 * Writes the plan catalog from src/plans/plans.registry.ts (the source of
 * truth) into the copies other repos read at build time:
 *
 *   ../MarketCatalystUI/app/admin/entitlement-catalog.ts   entitlement keys/labels
 *   ../MarketCatalystWebsite/lib/pricing/catalog.json        plans + prices (fallback
 *                                                            when GET /plans is down)
 *                                                            + the refund policy copy
 *   ../MarketCatalystUI/app/iq/billing/refund-policy.generated.ts  refund policy copy
 *   ../MarketCatalystUI/app/iq/feature-map.generated.ts     feature groups, screen/widget
 *                                                            gates, plan cards
 *   ../MarketCatalystUI/firestore.rules                      the GENERATED section
 *   docs/FEATURE-MAP.md                                      the feature map, readable
 *
 *   npx ts-node --transpile-only scripts/export-catalog.ts [--check]
 *
 * --check exits 1 if either copy is out of date (used by the contract test).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import {
  CATALOG_VERSION,
  CLIENT_DENIED_COLLECTIONS,
  ENTITLEMENTS,
  EVERY_PLAN_INCLUDES,
  FEATURE_GROUPS,
  PLAN_CARD_BULLETS,
  PLAN_DEFINITIONS,
  PLAN_EXEMPT_ROUTES,
  PLAN_EXEMPT_SCREENS,
  PLAN_GROUPS,
  ROUTE_FEATURES,
  SCREEN_FEATURES,
  WIDGET_FEATURES,
  groupOf,
  lowestPlanFor,
} from "../src/plans/plans.registry";
import { refundPolicy } from "../src/billing/refund/refund-policy";

const ROOT = join(__dirname, "..", "..");
const UI_CATALOG = join(
  ROOT,
  "MarketCatalystUI/app/admin/entitlement-catalog.ts",
);
const WEB_CATALOG = join(
  ROOT,
  "MarketCatalystWebsite/lib/pricing/catalog.json",
);
const UI_REFUND = join(
  ROOT,
  "MarketCatalystUI/app/iq/billing/refund-policy.generated.ts",
);
const UI_FEATURE_MAP = join(ROOT, "MarketCatalystUI/app/iq/feature-map.generated.ts");
const UI_RULES = join(ROOT, "MarketCatalystUI/firestore.rules");
const FEATURE_MAP_DOC = join(__dirname, "..", "docs/FEATURE-MAP.md");

export const RULES_BEGIN = "    // ── BEGIN GENERATED: feature map (scripts/export-catalog.ts) ──";
export const RULES_END = "    // ── END GENERATED: feature map ──";

const lowest = (k: string) => lowestPlanFor(k)?.id ?? null;

export function uiFeatureMapSource(): string {
  const active = PLAN_DEFINITIONS.filter((p) => p.active);
  const data = {
    FEATURE_GROUPS,
    PLAN_GROUPS,
    PLANS: active.map((p) => ({
      id: p.id,
      name: p.name,
      description: p.description,
      groups: PLAN_GROUPS[p.id],
      bullets: PLAN_CARD_BULLETS[p.id] ?? [],
    })),
    EVERY_PLAN_INCLUDES,
    SCREEN_FEATURES,
    WIDGET_FEATURES,
    PLAN_EXEMPT_SCREENS: [...PLAN_EXEMPT_SCREENS],
    FEATURE_GROUP_OF: Object.fromEntries(
      ENTITLEMENTS.filter((e) => e.featureGroup).map((e) => [e.key, e.featureGroup]),
    ),
    LOWEST_PLAN: Object.fromEntries(
      ENTITLEMENTS.filter((e) => e.featureGroup).map((e) => [e.key, lowest(e.key)]),
    ),
  };
  const body = Object.entries(data)
    .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`)
    .join("\n\n");
  return `// GENERATED by MarketCatalystBackEnd/scripts/export-catalog.ts from
// src/plans/plans.registry.ts — do not edit by hand; re-run the script.
// The backend's route-groups/catalog specs fail when this file drifts.

${body}
`;
}

/** The generated block of firestore.rules: plan ladder + client-denied collections. */
export function rulesSection(): string {
  const ladder = PLAN_DEFINITIONS.filter((p) => p.active)
    .sort((a, b) => a.sortOrder - b.sortOrder)
    .map((p) => p.id);
  const at = (min: string) =>
    `(minimum == '${min}' && plan() in [${ladder.slice(ladder.indexOf(min)).map((x) => `'${x}'`).join(", ")}])`;
  const lines = [
    RULES_BEGIN,
    "    // Plans in ladder order (no free plan; an account without a plan has none).",
    "    function planAtLeast(minimum) {",
    "      return " + ladder.map(at).join("\n          || ") + ";",
    "    }",
    "",
    "    // No browser reads these (every screen goes through the backend); they",
    "    // were plan-gated before. Client reads are denied outright.",
    ...CLIENT_DENIED_COLLECTIONS.map(
      (c) => `    match /${c}/{d=**} { allow read, write: if false; }`,
    ),
    RULES_END,
  ];
  return lines.join("\n");
}

/** firestore.rules with its generated section replaced (throws if the markers are missing). */
export function rulesWithSection(current: string): string {
  const a = current.indexOf(RULES_BEGIN);
  const b = current.indexOf(RULES_END);
  if (a === -1 || b === -1) throw new Error("firestore.rules: generated-section markers missing");
  return current.slice(0, a) + rulesSection() + current.slice(b + RULES_END.length);
}

export function featureMapDoc(): string {
  const planName = (id: string | null) => PLAN_DEFINITIONS.find((p) => p.id === id)?.name ?? "—";
  const out: string[] = [
    "# Feature map",
    "",
    "GENERATED by `scripts/export-catalog.ts` from `src/plans/plans.registry.ts`. Do not edit.",
    "",
    "## Plans",
    "",
    "| Plan | Feature groups |",
    "|---|---|",
    ...PLAN_DEFINITIONS.filter((p) => p.active).map(
      (p) => `| ${p.name} | ${PLAN_GROUPS[p.id].map((g) => FEATURE_GROUPS.find((x) => x.id === g)!.name).join(", ")} |`,
    ),
    "",
    "An account with no active plan can use only: " +
      PLAN_EXEMPT_ROUTES.map((e) => `\`${e.prefix}\` (${e.reason})`).join(", ") +
      ". Screens: " + PLAN_EXEMPT_SCREENS.join(", ") + ".",
    "",
  ];
  for (const g of FEATURE_GROUPS) {
    out.push(`## ${g.name} (${planName(lowest(ENTITLEMENTS.find((e) => e.featureGroup === g.id)!.key))} and up)`, "");
    out.push("| Feature | Screens | Widgets | Backend routes |", "|---|---|---|---|");
    for (const e of ENTITLEMENTS.filter((x) => x.featureGroup === g.id)) {
      const screens = Object.entries(SCREEN_FEATURES).filter(([, k]) => k === e.key).map(([s]) => s);
      const widgets = Object.entries(WIDGET_FEATURES).filter(([, k]) => k === e.key).map(([s]) => s);
      const routes = Object.entries(ROUTE_FEATURES)
        .filter(([, r]) => (r === "bars" ? ["chartsDaily", "chartsIntraday", "chartsHistory"] : r).includes(e.key))
        .map(([k]) => "`" + k + "`");
      out.push(`| ${e.label} | ${screens.join(", ") || "—"} | ${widgets.join(", ") || "—"} | ${routes.join("<br>") || "—"} |`);
    }
    out.push("");
  }
  out.push("## Firestore client reads", "", "Denied outright (no browser reads them): " + CLIENT_DENIED_COLLECTIONS.map((c) => "`" + c + "`").join(", ") + ".", "");
  void groupOf;
  return out.join("\n") + "\n";
}

export function uiRefundPolicySource(): string {
  return `// GENERATED by MarketCatalystBackEnd/scripts/export-catalog.ts from
// src/billing/refund/refund-policy.config.ts (REFUND_WINDOW_DAYS) — do not edit
// by hand; change that one line and re-run the script.

export const REFUND_POLICY = ${JSON.stringify(refundPolicy(), null, 2)} as const;
`;
}

export function uiCatalogSource(): string {
  const rows = ENTITLEMENTS.map(
    (e) =>
      "  { " +
      Object.entries(e)
        .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
        .join(", ") +
      " },",
  ).join("\n");
  return `// GENERATED by MarketCatalystBackEnd/scripts/export-catalog.ts from
// src/plans/plans.registry.ts — do not edit by hand; re-run the script.

export interface EntitlementDef {
  key: string;
  label: string;
  /** One plain sentence: what the user gets when this is ON. */
  description: string;
  group: string;
  featureGroup?: string;
  staffOnly?: boolean;
  unbuilt?: boolean;
  note?: string;
}

export const ENTITLEMENTS: EntitlementDef[] = [
${rows}
];
`;
}

export function websiteCatalogJson(): string {
  const plans = PLAN_DEFINITIONS.filter((p) => p.active).map((p) => ({
    id: p.id,
    name: p.name,
    description: p.description,
    currency: p.currency,
    prices: p.prices,
    groups: PLAN_GROUPS[p.id],
    bullets: PLAN_CARD_BULLETS[p.id] ?? [],
  }));
  return (
    JSON.stringify(
      {
        catalogVersion: CATALOG_VERSION,
        plans,
        everyPlanIncludes: EVERY_PLAN_INCLUDES,
        refundPolicy: refundPolicy(),
      },
      null,
      2,
    ) + "\n"
  );
}

function main() {
  const check = process.argv.includes("--check");
  const targets: Array<[string, string]> = [
    [UI_CATALOG, uiCatalogSource()],
    [WEB_CATALOG, websiteCatalogJson()],
    [UI_REFUND, uiRefundPolicySource()],
    [UI_FEATURE_MAP, uiFeatureMapSource()],
    [FEATURE_MAP_DOC, featureMapDoc()],
  ];
  if (existsSync(UI_RULES))
    targets.push([UI_RULES, rulesWithSection(readFileSync(UI_RULES, "utf8"))]);
  let stale = 0;
  for (const [path, content] of targets) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === content) continue;
    if (check) {
      console.error(`out of date: ${path}`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${path}`);
    }
  }
  if (check && stale) process.exit(1);
}

if (require.main === module) main();
